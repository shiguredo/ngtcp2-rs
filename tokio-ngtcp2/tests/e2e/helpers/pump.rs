//! クライアントとサーバーを交互に駆動するためのヘルパー

use std::time::Duration;

/// 交互駆動の 1 回あたりの待ち時間
///
/// ストリームは両方向が終端し、かつ送信データがすべて ACK されて初めて
/// 閉じる (RFC 9000 Section 3.3)。そのため片側だけを await すると ACK が
/// 流れず、もう片方のストリームが閉じない。両側を短いタイムアウト付きで
/// 交互に await することで、単一タスクのまま ACK を流し続けられる。
///
/// タイムアウトで `recv_event` の future が破棄されると、書き出し済みだが
/// 未送信のパケットが失われることがある。その場合は ngtcp2 の PTO による
/// 再送で回復するため、テストの正しさには影響しない。
pub(crate) const PUMP_INTERVAL: Duration = Duration::from_millis(20);
